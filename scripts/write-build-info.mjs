import { execSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));

function readCommand(command) {
  try {
    return execSync(command, { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
  } catch {
    return "";
  }
}

const envCommit =
  process.env.VERCEL_GIT_COMMIT_SHA ||
  process.env.CF_PAGES_COMMIT_SHA ||
  process.env.COMMIT_SHA ||
  process.env.GITHUB_SHA ||
  "";

const commitFull = readCommand("git rev-parse HEAD") || envCommit || "dev-local";
const commitShort = commitFull === "dev-local" ? "dev-local" : commitFull.slice(0, 7);
const buildTimeIso = new Date().toISOString().replace(/\.\d{3}Z$/, "Z");
const buildTimeLabel = new Intl.DateTimeFormat("en-US", {
  month: "short",
  day: "numeric",
  year: "numeric",
  hour: "2-digit",
  minute: "2-digit",
  hour12: false,
  timeZone: "UTC",
  timeZoneName: "short",
}).format(new Date(buildTimeIso)).replace(",", " ·");

const payload = {
  commitShort,
  commitFull,
  buildTimeIso,
  buildTimeLabel,
  buildCacheBuster: `${commitShort}-${buildTimeIso}`,
  pricingCodeVersion: commitFull,
};

const ts = `// Build metadata — regenerated by scripts/write-build-info.mjs on every build/publish.\nexport const BUILD_COMMIT_SHORT = ${JSON.stringify(payload.commitShort)};\nexport const BUILD_COMMIT_FULL = ${JSON.stringify(payload.commitFull)};\nexport const BUILD_TIME_ISO = ${JSON.stringify(payload.buildTimeIso)};\nexport const BUILD_TIME_LABEL = ${JSON.stringify(payload.buildTimeLabel)};\nexport const BUILD_CACHE_BUSTER = ${JSON.stringify(payload.buildCacheBuster)};\nexport const LATEST_PRICING_CODE_VERSION = ${JSON.stringify(payload.pricingCodeVersion)};\n`;

writeFileSync(join(root, "src/lib/buildInfo.ts"), ts);
mkdirSync(join(root, "public"), { recursive: true });
writeFileSync(join(root, "public/build-info.json"), `${JSON.stringify(payload, null, 2)}\n`);
writeFileSync(join(root, "public/pricing-version.json"), `${JSON.stringify({ pricingCodeVersion: payload.pricingCodeVersion, commitFull: payload.commitFull, buildTimeIso: payload.buildTimeIso }, null, 2)}\n`);

console.log(`build info: ${commitShort} ${buildTimeIso}`);