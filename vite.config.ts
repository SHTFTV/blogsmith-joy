import { defineConfig } from "@lovable.dev/vite-tanstack-config";
import { loadEnv } from "vite";
import path from "node:path";

// Load ALL env vars into process.env so server routes can read
// SUPABASE_SERVICE_ROLE_KEY etc. (non-VITE_ vars). Client bundles still only
// receive VITE_-prefixed vars via the wrapper's envDefine.
const serverEnv = loadEnv(process.env.NODE_ENV || "development", process.cwd(), "");
Object.assign(process.env, serverEnv);

export default defineConfig({
  vite: {
    resolve: {
      alias: {
        // Pin every `entities` import to the hoisted v4.5.0 copy — v5+ removed
        // `entities/lib/decode.js` which React Email's htmlparser2 needs.
        "entities/lib/decode.js": path.resolve(
          process.cwd(),
          "node_modules/entities/lib/decode.js",
        ),
        "entities/lib/encode.js": path.resolve(
          process.cwd(),
          "node_modules/entities/lib/encode.js",
        ),
        entities: path.resolve(process.cwd(), "node_modules/entities"),
      },
    },
  },
});
